"""Generate the default-component reference without fitting any estimators.

Run after installing ``.[all,docs]`` with ``-c docs/constraints.txt``.
The mappings identify model roles; parameter values come from constructed
objects or their upstream constructor signatures. Fit-time behavior belongs
in docs/components.md, with versioned source references.
"""

from __future__ import annotations

import argparse
import difflib
import inspect
import json
from importlib.metadata import version
from pathlib import Path

from xcausal import CausalEnsemble
from xcausal.adapters import CausalMLAdapter, DoubleMLAdapter, StochtreeAdapter
from xcausal.defaults import default_methods


ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "docs" / "_generated" / "components.md"


def render() -> str:
    """Return a deterministic Markdown snapshot of both default pools."""
    import tomllib

    constraints = ROOT / "docs" / "constraints.txt"
    project = tomllib.loads((ROOT / "pyproject.toml").read_text())["project"]
    requirements = project["optional-dependencies"]["all"] + project["dependencies"]
    lines = [
        "<!-- Generated by scripts/generate_component_docs.py; do not edit. -->",
        "", "## Documentation environment", "",
        "Inherited defaults below are resolved in this environment. Package support",
        "ranges can include other versions; upstream behavior can differ between them.",
        "", "| Dependency | Documented version | Package requirement |",
        "|---|---|---|",
    ]
    for entry in constraints.read_text().splitlines():
        if not entry or entry.startswith("#"):
            continue
        package, expected = entry.split("==")
        actual = version(package)
        if actual != expected:
            raise ValueError(
                f"{package}=={actual} installed; documentation requires {entry}. "
                "Install with: pip install -e '.[all,docs]' -c docs/constraints.txt"
            )
        requirement = next((r for r in requirements if r.startswith(package + ">=")), None)
        if requirement is None:
            raise ValueError(f"No package requirement found for documented dependency {package}")
        lines.append(f"| {package} | {actual} | `{requirement}` |")

    recipes: list[tuple[str, dict]] = []

    def model_ref(model) -> str:
        name = type(model).__name__
        # Full shallow parameter dictionaries catch changes to defaults as well
        # as explicit overrides. Avoid repr(), which hides default parameters.
        params = model.get_params(deep=False)
        json.dumps(params, sort_keys=True, allow_nan=False)  # fail on unsupported new recipes
        recipe = (name, params)
        if recipe not in recipes:
            recipes.append(recipe)
        return f"[{name}](#model-{recipes.index(recipe) + 1})"

    def settings(model, *names) -> dict:
        return {name: getattr(model, name) for name in names}

    def resolve(component):
        if isinstance(component, DoubleMLAdapter):
            cls = component._model_class
            name = cls.__name__
            outcome_slot = {"DoubleMLIRM": "ml_g", "DoubleMLPLR": "ml_l"}[name]
            signature = inspect.signature(cls)
            config = {
                key: component._kwargs.get(key, param.default)
                for key, param in signature.parameters.items()
                if param.default is not inspect.Parameter.empty
                and key not in ("ml_g", "ml_l", "ml_m")
            }
            return (model_ref(component._kwargs[outcome_slot]),
                    model_ref(component._kwargs["ml_m"]), "ATE score; no CATE model", config)

        if isinstance(component, StochtreeAdapter):
            return ("BCF prognostic forest", model_ref(component._propensity_model),
                    "BCF treatment-effect forest", settings(
                        component, "num_gfr", "num_burnin", "num_mcmc",
                        "propensity_n_splits", "propensity_clip_eps", "general_params",
                        "prognostic_forest_params", "treatment_effect_forest_params"))

        model = component._model if isinstance(component, CausalMLAdapter) else component
        name = type(model).__name__
        if name == "CausalForestDML":
            return (model_ref(model.model_y), model_ref(model.model_t), "EconML causal forest",
                    settings(model, "cv", "discrete_outcome", "discrete_treatment", "featurizer",
                             "n_estimators", "criterion", "honest", "max_samples", "max_depth",
                             "min_samples_leaf", "min_samples_split", "n_jobs"))
        if name == "DRLearner":
            return (model_ref(model.model_regression), model_ref(model.model_propensity),
                    model_ref(model.model_final), settings(
                        model, "cv", "discrete_outcome", "min_propensity",
                        "trimming_threshold", "featurizer", "multitask_model_final"))
        if name == "TLearner":
            return (model_ref(model.models), "Not used", "Difference of outcome regressions", {})
        if name == "XLearner":
            effect = ("Fresh clones of " + model_ref(model.models)
                      if model.cate_models is None else model_ref(model.cate_models))
            return (model_ref(model.models), model_ref(model.propensity_model), effect,
                    {"cate_models": None} if model.cate_models is None else {})
        if name in ("BaseRRegressor", "BaseRClassifier"):
            return (model_ref(model.outcome_learner), model_ref(model.propensity_learner),
                    model_ref(model.effect_learner), settings(model, "n_fold", "cv_n_jobs"))
        if name == "BaseTClassifier":
            control = model.control_learner if model.control_learner is not None else model.learner
            treatment = model.treatment_learner if model.treatment_learner is not None else model.learner
            return (f"Control: {model_ref(control)}; treatment: {model_ref(treatment)}",
                    "Not used", "Difference of outcome probabilities", {})
        if name == "BaseXClassifier":
            outcome = []
            effect = []
            for group in ("control", "treatment"):
                out = getattr(model, group + "_outcome_learner")
                eff = getattr(model, group + "_effect_learner")
                outcome.append(model_ref(model.outcome_learner if out is None else out))
                effect.append(model_ref(model.effect_learner if eff is None else eff))
            return ("Control / treatment: " + " / ".join(outcome),
                    model_ref(component._propensity_model),
                    "Control / treatment: " + " / ".join(effect), {})
        if name == "TMLELearner":
            return (model_ref(model.model_tau), model_ref(component._propensity_model),
                    "Targeted update (ATE only)", settings(model, "cv"))
        raise ValueError(f"No documentation mapping for component {type(model).__module__}.{name}")

    for pool in ("continuous", "binary"):
        components = default_methods(pool)
        # Reuse the ensemble's real wrapping/capability logic without fitting.
        adapters = CausalEnsemble(methods=components)._wrapped_methods
        cate_count = sum(adapter.supports_cate for adapter in adapters)
        lines += ["", f"## {pool.capitalize()} pool", "",
                  f"{len(components)} components; {cate_count} support CATE. "
                  "Every listed component supports ATE.", "",
                  "| Component | Outcome / prognostic | Propensity | Effect | CATE |",
                  "|---|---|---|---|---|"]
        configs = []
        for component, adapter in zip(components, adapters, strict=True):
            outcome, propensity, effect, config = resolve(component)
            lines.append(f"| `{adapter.name}` | {outcome} | {propensity} | {effect} | "
                         f"{'Yes' if adapter.supports_cate else 'No'} |")
            if config:
                configs.append((adapter.name, config))
        lines += ["", "### Resolved settings", "",
                  "XCausal supplies the model recipes above. The settings below include",
                  "both explicit XCausal choices and inherited constructor defaults; see",
                  "the construction notes for their origins and fit-time behavior.", ""]
        for name, config in configs:
            lines += [f"**{name}**", "", "```json", json.dumps(config, indent=2, sort_keys=True), "```", ""]

    lines += ["## Model recipes", "",
              "These are unfitted templates. Repeated recipe references describe matching",
              "configurations, not a shared fitted estimator. Parameters are read from",
              "the actual templates, including inherited upstream defaults."]
    for i, (name, params) in enumerate(recipes, 1):
        lines += ["", f"### Model {i}", "", f"`{name}`", "", "```json",
                  json.dumps(params, indent=2, sort_keys=True), "```"]
    return "\n".join(lines).rstrip() + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if generated documentation is stale")
    parser.add_argument("--output", type=Path, default=OUTPUT)
    args = parser.parse_args()
    try:
        content = render()
    except (ValueError, KeyError, AttributeError, TypeError) as exc:
        parser.exit(1, f"Component documentation: {exc}\n")
    if args.check:
        existing = args.output.read_text() if args.output.exists() else ""
        if existing != content:
            print("".join(difflib.unified_diff(existing.splitlines(True), content.splitlines(True),
                                               fromfile=str(args.output), tofile="generated")))
            print("Component documentation is stale. Run: python scripts/generate_component_docs.py")
            return 1
    else:
        args.output.parent.mkdir(parents=True, exist_ok=True)
        args.output.write_text(content)
        print(f"Updated {args.output}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
